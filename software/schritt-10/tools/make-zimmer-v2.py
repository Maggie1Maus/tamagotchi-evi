"""Install the verified native layers from the approved v2 graphics archive."""
import hashlib,json,zipfile
from pathlib import Path
root=Path(__file__).resolve().parents[3]
source=root/'entwuerfe/zimmer/grillme-2026-11-25/v2/Evi_Grafikpaket_V2.zip'
with zipfile.ZipFile(source) as z:
 prefix='evi-grafikpaket-v2-2026-11-25/'
 checks=json.loads(z.read(prefix+'SHA256.json'))
 for name,digest in checks.items():
  if hashlib.sha256(z.read(prefix+name)).hexdigest()!=digest:raise ValueError('Checksum mismatch: '+name)
 header=z.read(prefix+'integration/evi_grafiken.h').decode()
 suffix=[]
 times=['TAG','DAEMMERUNG','NACHT'];weather=['KLAR','LEICHT_BEWOELKT','REGEN','BEDECKT','SCHNEEFALL']
 for name,prefix in [('Z_HIMMEL','HIMMEL'),('Z_ZEICHEN','HIMMELSZEICHEN'),('Z_WOLKEN','WOLKEN')]:
  suffix.append('static const EviGrafik* const '+name+'[3][5] = {')
  for time in times:suffix.append('{'+','.join('&EVI_'+prefix+'_'+time+'_'+w for w in weather)+'},')
  suffix.append('};')
 for name,ids in [('Z_BAEUME',['BAUM_'+s for s in ['FRUEHLING','SOMMER','HERBST','WINTER']]),('Z_REGEN',['REGEN_%02d'%i for i in range(16)]),('Z_SCHNEE',['SCHNEEFALL_%02d'%i for i in range(16)])]:suffix.append('static const EviGrafik* const '+name+'[] = {'+','.join('&EVI_'+a for a in ids)+'};')
 (root/'software/schritt-10/evi-handy/zimmergrafiken.h').write_text('// Generated by tools/make-zimmer-v2.py; approved graphics v2.\n'+header+'\n'+'\n'.join(suffix)+'\n')
 print('Installed approved layers; all archive checksums verified.')
