"""Install verified v2 layers and the requested twilight/night tree palettes."""
import binascii,hashlib,json,re,struct,zipfile,zlib
from pathlib import Path
root=Path(__file__).resolve().parents[3]
folder=root/'entwuerfe/zimmer/grillme-2026-11-25/v2'
source=folder/'Evi_Grafikpaket_V2.zip'
seasons=['fruehling','sommer','herbst','winter']
times=['tag','daemmerung','nacht']
weather=['klar','leicht-bewoelkt','regen','bedeckt','schneefall']

def pack(bits,w,h):
 data=bytearray(((w+7)//8)*h)
 for y in range(h):
  for x in range(w):
   if bits[y*w+x]:data[y*((w+7)//8)+x//8]|=128>>(x%8)
 return data

def png(file,bits,w,h):
 def chunk(kind,data):return struct.pack('>I',len(data))+kind+data+struct.pack('>I',binascii.crc32(kind+data)&0xffffffff)
 stride=(w+7)//8;packed=pack([not b for b in bits],w,h)
 rows=b''.join(b'\0'+packed[y*stride:(y+1)*stride] for y in range(h))
 file.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',w,h,1,0,0,0,0))+chunk(b'IDAT',zlib.compress(rows))+chunk(b'IEND',b''))

with zipfile.ZipFile(source) as z:
 archive_root='evi-grafikpaket-v2-2026-11-25/'
 checks=json.loads(z.read(archive_root+'SHA256.json'))
 for name,digest in checks.items():
  if hashlib.sha256(z.read(archive_root+name)).hexdigest()!=digest:raise ValueError('Checksum mismatch: '+name)
 manifest=json.loads(z.read(archive_root+'manifest.json'))
 header=z.read(archive_root+'integration/evi_grafiken.h').decode()
 cache={}
 def bitmap(name):
  raw=z.read(archive_root+name);match=re.match(rb'P4\n(\d+) (\d+)\n',raw)
  w,h=map(int,match.groups());data=raw[match.end():];stride=(w+7)//8
  return [bool(data[y*stride+x//8]&(128>>(x%8))) for y in range(h) for x in range(w)]
 def asset(name):
  if name not in cache:
   meta=manifest['assets'][name]
   cache[name]={'w':meta['width'],'h':meta['height'],'ink':bitmap(meta['ink']),'mask':bitmap(meta['mask']) if meta['mask'] else None}
  return cache[name]
 def overlay(dst,a,ox=0,oy=0):
  for y in range(a['h']):
   for x in range(a['w']):
    i=y*a['w']+x;px=x+ox;py=y+oy
    if 0<=px<66 and 0<=py<53 and (a['mask'] is None or a['mask'][i]):dst[py*66+px]=a['ink'][i]

 suffix=[];styled={}
 for season in seasons:
  original=asset('baum-'+season);ink=original['ink'];mask=original['mask']
  # Preserve the existing solid body and its one-pixel clearance as the contrasting rim.
  body=[]
  for y in range(53):
   for x in range(66):
    interior=all(0<=x+dx<66 and 0<=y+dy<53 and mask[(y+dy)*66+x+dx] for dy in (-1,0,1) for dx in (-1,0,1))
    body.append(ink[y*66+x] or interior)
  for palette in ['daemmerung','nacht']:
   values=[m and not b for m,b in zip(mask,body)] if palette=='daemmerung' else body
   styled[season,palette]={'w':66,'h':53,'ink':values,'mask':mask}
   identifier='EVI_BAUM_'+palette.upper()+'_'+season.upper()
   data=pack(values,66,53);suffix.append('static const uint8_t '+identifier+'_LINIEN[] = {')
   for i in range(0,len(data),20):suffix.append('  '+','.join('0x%02x'%v for v in data[i:i+20])+',')
   suffix.append('};')
   suffix.append(f'static const EviGrafik {identifier} = {{66,53,{identifier}_LINIEN,EVI_BAUM_{season.upper()}_MASKE}};')
 for name,prefix in [('Z_HIMMEL','HIMMEL'),('Z_ZEICHEN','HIMMELSZEICHEN'),('Z_WOLKEN','WOLKEN')]:
  suffix.append('static const EviGrafik* const '+name+'[3][5] = {')
  for time in times:suffix.append('{'+','.join('&EVI_'+prefix+'_'+time.upper()+'_'+w.upper().replace('-','_') for w in weather)+'},')
  suffix.append('};')
 for name,ids in [
  ('Z_BAEUME',['BAUM_'+s.upper() for s in seasons]),
  ('Z_BAEUME_ABEND',['BAUM_DAEMMERUNG_'+s.upper() for s in seasons]),
  ('Z_BAEUME_NACHT',['BAUM_NACHT_'+s.upper() for s in seasons]),
  ('Z_REGEN',['REGEN_%02d'%i for i in range(16)]),('Z_SCHNEE',['SCHNEEFALL_%02d'%i for i in range(16)])]:
  suffix.append('static const EviGrafik* const '+name+'[] = {'+','.join('&EVI_'+a for a in ids)+'};')
 (root/'software/schritt-10/evi-handy/zimmergrafiken.h').write_text('// Generated by tools/make-zimmer-v2.py; v2 art with approved twilight/night palette.\n'+header+'\n'+'\n'.join(suffix)+'\n')

 # Current reference PNG; the original graphics ZIP remains unchanged.
 rows=[(s,w) for s in seasons for w in weather if w!='schneefall' or s=='winter']
 atlas=[False]*(198*len(rows)*53);states=[]
 for row,(season,rain) in enumerate(rows):
  for col,time in enumerate(times):
   dst=list(asset('himmel-'+time+'-'+rain)['ink'])
   if time!='daemmerung':overlay(dst,asset('himmelszeichen-'+time+'-'+rain))
   overlay(dst,asset('wolken-'+time+'-'+rain))
   if time=='daemmerung' and rain=='leicht-bewoelkt':overlay(dst,asset('wetter-wolke'),4,18)
   overlay(dst,asset('landschaft-huegel-boden'))
   overlay(dst,asset('baum-'+season) if time=='tag' else styled[season,time])
   if season=='herbst':overlay(dst,asset('herbstlaub-boden'));overlay(dst,asset('herbstblatt'),19,28)
   if rain in ['regen','schneefall']:overlay(dst,asset(rain+'-00'))
   for y in range(53):atlas[(row*53+y)*198+col*66:(row*53+y)*198+(col+1)*66]=dst[y*66:(y+1)*66]
   states.append({'id':f'{season}-{time}-{rain}','x':col*66,'y':row*53})
 png(folder/'Fenster_aktuell.png',atlas,198,len(rows)*53)
 (folder/'Fenster_aktuell.json').write_text(json.dumps({'width':66,'height':53,'atlas':'Fenster_aktuell.png','states':states},indent=2)+'\n')
 print('Installed verified layers and current twilight/night references for 51 combinations.')
